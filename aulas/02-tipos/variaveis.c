int main() {  
  /* ----------------------- */
  /* Declaração de Variáveis */
  /* ----------------------- */

  //┌──────> tipo (inteiro) 
  int x;
  //  └────> nome 
  
  /* Declaração com inicialização */

  //           ┌──────> valor inicial
  int idade = 19;
  // │      └──────> atribuição
  // └────────────> tipo e nome

  /* ------------------- */
  /* Declaração múltipla */
  /* ------------------- */

  // Sem inicialização:
  int a, b, c;

  // Com inicialização:
  int nota = 90, pontos = 10;

  // Com inicialização (parcial)
  int n1 = 5, n2, n3 = 7;

  return 0;
}
